// Writes src/shared/api/attentionCommands.generated.ts from the `x-xdrishti-attention-commands` extension of the API contract
// (backend/contracts/XDrishti.Api.json), which the backend builds from AttentionCommands.Allowed (XDrishti.Application/Portfolio/Attention):
// the one list of the commands a notice may carry (ADR 0030). The client allows itself to send exactly these and nothing else.
// Run by `npm run gen:api` (scripts/gen-api.sh). Never edit the output by hand.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const contractPath = resolve(root, '../backend/contracts/XDrishti.Api.json');
const outPath = resolve(root, 'src/shared/api/attentionCommands.generated.ts');

const contract = JSON.parse(readFileSync(contractPath, 'utf8'));
const commands = contract['x-xdrishti-attention-commands'];
if (!Array.isArray(commands) || commands.length === 0) {
  throw new Error(`${contractPath} has no x-xdrishti-attention-commands: build the API with scripts/gen-api.sh first.`);
}

for (const command of commands) {
  for (const key of ['name', 'method', 'template', 'pattern']) {
    if (typeof command[key] !== 'string' || command[key] === '')
      throw new Error(`An attention command of the contract has no ${key}.`);
  }
  new RegExp(command.pattern); // a pattern the browser cannot compile is a build error, not a runtime surprise
}

const entries = commands.map(
  (c) =>
    `  { name: ${JSON.stringify(c.name)}, method: ${JSON.stringify(c.method)}, template: ${JSON.stringify(c.template)}, pattern: ${JSON.stringify(c.pattern)} },`,
);

const text = [
  '// <auto-generated>',
  '// From backend/contracts/XDrishti.Api.json (x-xdrishti-attention-commands) by frontend/scripts/gen-attention-commands.mjs.',
  '// Do not edit by hand: change AttentionCommands (XDrishti.Application/Portfolio/Attention) and run scripts/gen-api.sh.',
  '// </auto-generated>',
  '',
  '/** A command a notice may carry: the HTTP method, the path with its placeholders and the whole-path pattern (a regular expression source). */',
  'export interface AttentionCommandPattern {',
  '  readonly name: string;',
  '  readonly method: string;',
  '  readonly template: string;',
  '  readonly pattern: string;',
  '}',
  '',
  '/** Every command the API can name in a notice, in the order of the server list. The client sends nothing else. */',
  'export const attentionCommands: readonly AttentionCommandPattern[] = [',
  ...entries,
  '];',
  '',
].join('\n');

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, text);
