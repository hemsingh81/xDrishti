// Writes src/shared/realtime/hubContract.generated.ts from the `x-xdrishti-hubs` extension of the API contract
// (backend/contracts/XDrishti.Api.json), which the backend builds from its C# contract (LiveHubContract and the message
// types). OpenAPI cannot describe a SignalR hub, so the names, argument and result types and payloads come from there;
// the message shapes themselves are the component schemas, typed by openapi-typescript in src/shared/api/schema.d.ts.
// Run by `npm run gen:api` (scripts/gen-api.sh). Never edit the output by hand.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const contractPath = resolve(root, '../backend/contracts/XDrishti.Api.json');
const outPath = resolve(root, 'src/shared/realtime/hubContract.generated.ts');

const contract = JSON.parse(readFileSync(contractPath, 'utf8'));
const hubs = contract['x-xdrishti-hubs'];
const schemas = contract.components?.schemas ?? {};
if (!hubs || Object.keys(hubs).length === 0) {
  throw new Error(`${contractPath} has no x-xdrishti-hubs: build the API with scripts/gen-api.sh first.`);
}

const pascal = (text) => text.replace(/(^|[-_/])(\w)/g, (_, __, c) => c.toUpperCase());
const camel = (text) => pascal(text).replace(/^\w/, (c) => c.toLowerCase());
const used = new Set();
const need = (type) => {
  if (!schemas[type])
    throw new Error(`The hub contract names the type ${type}, which is not a schema of the API contract.`);
  used.add(type);
  return type;
};

const sections = [];
for (const [route, hub] of Object.entries(hubs)) {
  const base = pascal(route.split('/').filter(Boolean).at(-1)) + 'Hub';
  const constName = camel(base);
  for (const type of hub.types ?? []) need(type);
  const methods = Object.entries(hub.methods);
  const events = Object.entries(hub.events);

  const server = methods.map(([name, m]) => {
    const args = m.arguments.map((a) => `${a.name}: ${need(a.type)}`).join(', ');
    const result = m.returns ? need(m.returns) : 'void';
    return `  ${name}(${args}): Promise<${result}>;`;
  });
  const handlers = events.map(([name, e]) => `  ${name}: (message: ${need(e.payload)}) => void;`);

  sections.push(
    [
      `/** The hub ${route}: its route, the names of the server methods and client events, and the bounds the server keeps. */`,
      `export const ${constName} = {`,
      `  route: ${JSON.stringify(route)},`,
      `  transport: ${JSON.stringify(hub.transport)},`,
      `  methods: { ${methods.map(([name]) => `${camel(name)}: ${JSON.stringify(name)}`).join(', ')} },`,
      `  events: { ${events.map(([name]) => `${name}: ${JSON.stringify(name)}`).join(', ')} },`,
      `  limits: ${JSON.stringify(hub.limits ?? {})},`,
      `} as const;`,
      ``,
      `/** Methods the client invokes on ${route} (\`connection.invoke(name, ...args)\`). */`,
      `export interface ${base}Server {`,
      ...server,
      `}`,
      ``,
      `/** Events ${route} sends to the client (\`connection.on(name, handler)\`). */`,
      `export interface ${base}Events {`,
      ...handlers,
      `}`,
    ].join('\n'),
  );
}

const header = [
  '// <auto-generated>',
  '// From backend/contracts/XDrishti.Api.json (x-xdrishti-hubs) by frontend/scripts/gen-hub-contract.mjs.',
  '// Do not edit by hand: change the C# contract (XDrishti.Application/Live/Push) and run scripts/gen-api.sh.',
  '// </auto-generated>',
  `import type { components } from '../api/schema';`,
  '',
  ...[...used].sort().map((type) => `export type ${type} = components['schemas']['${type}'];`),
  '',
].join('\n');

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, `${header}\n${sections.join('\n\n')}\n`);
