using System.Text.Json;

namespace XDrishti.Application.Tests.Portfolio.Live.Golden;

/// <summary>
/// The golden file for the browser's live recompute (P2-10a, ADR 0024 §7): the real <c>HoldingViews.Row</c>, <c>GetHoldingsSummaryHandler</c> and <c>GetHoldingGroupsHandler</c> (so <c>ReturnsCalculator</c>, <c>DayChangeCalculator</c> and
/// <c>GroupCalculator</c>) over made-up holdings, before and after prices pushed over the hub, written to <c>frontend/src/test/fixtures/liveGolden.json</c>. The frontend tests load that file and assert its recompute equals the "after"
/// exactly, so the browser is held to the C# arithmetic and not to a second port of it. The test fails when the checked-in file differs from what the calculators produce; set <c>XD_UPDATE_GOLDEN=1</c> to rewrite it. (The one test in
/// this project that touches the disk: the file is the contract between the two test suites.)
/// </summary>
public sealed class LiveGoldenTests
{
    private const string UpdateVariable = "XD_UPDATE_GOLDEN";

    private const string Note =
        "Generated by XDrishti.Application.Tests LiveGoldenTests from the real server calculators; never edit by hand (XD_UPDATE_GOLDEN=1 dotnet test --solution XDrishti.slnx -c Release rewrites it). " +
        "Money and percentages are rounded to 4 decimals, halves away from zero, as the API does; every xirr is null (not recomputed by the browser).";

    private static readonly JsonSerializerOptions Json = new(JsonSerializerDefaults.Web);

    private static GoldenFile Build() => new(1, Note, GoldenWorld.Valuation, GoldenCases.All());

    /// <summary>One scenario per line, so a change shows as a change of that scenario.</summary>
    private static string Render(GoldenFile file)
    {
        var header = JsonSerializer.Serialize(new { file.Schema, file.Note, file.ValuationDate }, Json);
        var scenarios = string.Join(",\n", file.Scenarios.Select(s => JsonSerializer.Serialize(s, Json)));
        return header[..^1] + ",\"scenarios\":[\n" + scenarios + "\n]}\n";
    }

    private static string FixturePath()
    {
        var directory = new DirectoryInfo(AppContext.BaseDirectory);
        while (directory is not null && !Directory.Exists(Path.Combine(directory.FullName, "frontend", "src", "test")))
        {
            directory = directory.Parent;
        }

        directory.ShouldNotBeNull("the repository root (the folder with frontend/src/test) was not found above the test binaries");
        return Path.Combine(directory.FullName, "frontend", "src", "test", "fixtures", "liveGolden.json");
    }

    [Fact]
    public void The_checked_in_golden_file_is_what_the_server_calculators_produce()
    {
        var path = FixturePath();
        var produced = Render(Build());

        if (Environment.GetEnvironmentVariable(UpdateVariable) == "1")
        {
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, produced);
            return;
        }

        File.Exists(path).ShouldBeTrue($"{path} is missing; run the tests once with {UpdateVariable}=1 to write it");
        var checkedIn = File.ReadAllText(path).Replace("\r\n", "\n", StringComparison.Ordinal);
        (checkedIn == produced).ShouldBeTrue($"{path} is stale: the server calculators produce something else. Review the change, then run the tests with {UpdateVariable}=1 to rewrite it and commit the file.");
    }

    [Fact]
    public void The_cases_cover_every_rule_the_browser_must_reproduce()
    {
        var file = Build();
        var before = file.Scenarios.SelectMany(s => s.Before.Rows).ToList();
        var after = file.Scenarios.SelectMany(s => s.After.Rows).ToList();
        var open = before.Where(r => r.Status == "open").ToList();

        var holdings = file.Scenarios.SelectMany(s => s.Holdings).ToList();

        file.Scenarios.Select(s => s.Name).Distinct().Count().ShouldBe(file.Scenarios.Count);
        file.Scenarios.Any(s => s.Holdings.Count >= 150).ShouldBeTrue("a case with many rows");
        open.Select(r => r.PriceSource).Distinct().Order().ShouldBe(["live", "quote", "sync"]);
        open.Any(r => r.PriceSource == "live" && r.DayChange is null && r.PreviousClose is not null).ShouldBeTrue("a live price whose close is not of the day");
        open.Any(r => r.PriceSource == "live" && r.DayChange is not null).ShouldBeTrue("a live price with a day change");
        open.Any(r => r.PriceSource == "sync" && r.DayChange is not null).ShouldBeTrue("a synced price with a day change");
        open.Any(r => !r.Priced).ShouldBeTrue("an unpriced holding");
        open.Any(r => r.InstrumentId is null).ShouldBeTrue("an unmapped holding");
        before.Any(r => r.Status == "closed").ShouldBeTrue("a closed holding");
        holdings.Any(h => h.Status == "open" && h.Lots.Any(l => l.ClosedOn is not null) && h.Lots.Any(l => l.ClosedOn is null)).ShouldBeTrue("a partly closed holding");
        holdings.Any(h => h.Status == "open" && h.Qty != h.Lots.Where(l => l.ClosedOn is null).Sum(l => l.Qty)).ShouldBeTrue("a broker quantity that differs from the open lots'");
        holdings.Any(h => h.LastPrice != decimal.Round(h.LastPrice, 2)).ShouldBeTrue("a sub-paise price");
        before.Zip(after).Count(pair => pair.First.LastPrice != pair.Second.LastPrice).ShouldBeGreaterThan(100); // the pushes change prices
        after.Any(r => r.PriceSource == "quote" && r.DayChange is not null).ShouldBeTrue("a quote pushed");
        file.Scenarios.Any(s => s.After.Summary.DayChange is null && s.After.Summary.DayChangeExcluded > 0).ShouldBeTrue("no day change at all");
        file.Scenarios.Any(s => s.Before.Groups.All.Account.Groups.Any(g => g.Value is null)).ShouldBeTrue("a group of only unpriced holdings");
        file.Scenarios.Any(s => s.After.Groups.All.Sector.Groups.Any(g => g.Key == "~none")).ShouldBeTrue("the Unclassified sector");
        file.Scenarios.ShouldAllBe(s => s.Pushes.Count > 0 && s.After.Rows.Count == s.Before.Rows.Count);
    }

    [Fact]
    public void The_golden_holdings_have_prices_of_at_most_four_decimals_like_the_columns()
    {
        var holdings = Build().Scenarios.SelectMany(s => s.Holdings).ToList();

        holdings.ShouldAllBe(h => h.LastPrice == decimal.Round(h.LastPrice, 4));
        holdings.ShouldAllBe(h => h.PreviousClose == null || h.PreviousClose == decimal.Round(h.PreviousClose.Value, 4));
        holdings.SelectMany(h => h.Lots).ShouldAllBe(l => l.UnitCost == decimal.Round(l.UnitCost, 4));
    }
}
